// Shared helpers for the app-review media pack (docs/APP_REVIEW.md):
//   - the manifest (scripts/review-pack/manifest.json): sources, licences, hashes, measured BPM / key
//   - prepareTracks(): regenerates the original tracks (scripts/demo/make-demo-library.mjs) and downloads the CC0 ones
//     from their official Free Music Archive pages, re-checking the CC0 licence on the page every time
//   - analyseFile(): BPM / key with OpenDJ's own analysis (public/js/audio/analysis-core.js), decoded by ffmpeg
//   - creditsMarkdown(), checksumsText(), writeZip()
// Used by build-review-pack.mjs, store-screenshots.mjs and store-video.mjs.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import zlib from 'node:zlib';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { makeDemoLibrary, ffmpegPath } from '../demo/make-demo-library.mjs';
import { analyzeTrack, toCamelot } from '../../public/js/audio/analysis-core.js';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const MANIFEST = path.join(ROOT, 'scripts/review-pack/manifest.json');
export const VERSION = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;
export const DEFAULT_CACHE = path.join(os.tmpdir(), 'opendj-review-pack-tracks');
const CC0_URL = 'https://creativecommons.org/publicdomain/zero/1.0/';
const FMA_HOSTS = new Set(['freemusicarchive.org', 'files.freemusicarchive.org']);
const USER_AGENT = 'OpenDJ-review-pack (+https://github.com/Bucifer6/OpenDJ)';

export const loadManifest = () => JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
export const saveManifest = (m) => fs.writeFileSync(MANIFEST, `${JSON.stringify(m, null, 2)}\n`);
export const sha256File = (f) => crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex');

/**
 * Node's fetch ignores HTTPS_PROXY unless NODE_USE_ENV_PROXY=1 (Node >= 22.21). Re-run this process with it set
 * when a proxy is configured, so downloads work behind one. Call at the top of a CLI script.
 */
export function ensureProxyEnv() {
  const proxy = process.env.HTTPS_PROXY || process.env.https_proxy;
  if (!proxy || process.env.NODE_USE_ENV_PROXY) return;
  const r = spawnSync(process.execPath, ['--no-warnings=ExperimentalWarning', ...process.execArgv, ...process.argv.slice(1)], { stdio: 'inherit', env: { ...process.env, NODE_USE_ENV_PROXY: '1', NODE_NO_WARNINGS: '1' } });
  process.exit(r.status ?? 1);
}

const NOTE = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'];
const generatorDef = (t) => ({
  artist: t.artist, title: t.title, album: t.album, genre: t.genre, year: t.year, file: t.file,
  bpm: t.generator.bpm, key: t.generator.key, style: t.generator.style, seed: t.generator.seed,
  comment: 'Original demo track generated by OpenDJ (scripts/demo/make-demo-library.mjs). Released under CC0 1.0 by the OpenDJ project.',
});
export const generatorKey = (t) => NOTE[t.generator.key[0]] + (t.generator.key[1] === 'minor' ? 'm' : '');

/** Fetch a CC0 track's page and check that it still shows CC0 1.0 for this exact track. Throws when not. */
export async function verifyFmaPage(t) {
  const u = new URL(t.pageUrl);
  if (u.protocol !== 'https:' || u.hostname !== 'freemusicarchive.org') throw new Error(`${t.title}: page is not on freemusicarchive.org`);
  const res = await fetch(u, { headers: { 'User-Agent': USER_AGENT }, signal: AbortSignal.timeout(30000) });
  if (!res.ok) throw new Error(`${t.title}: track page returned HTTP ${res.status}`);
  const html = await res.text();
  const m = /data-track-info='([^']+)'/.exec(html);
  if (!m) throw new Error(`${t.title}: no track info on the page`);
  const info = JSON.parse(m[1].replace(/&quot;/g, '"').replace(/&amp;/g, '&'));
  if (info.title !== t.title || info.artistName !== t.artist) throw new Error(`${t.title}: the page is for "${info.title}" by ${info.artistName}`);
  // the licence statement of the track ("<title> by <artist> is licensed under a CC0 1.0 Universal License")
  const lic = /licensed under a <a rel="license" href="([^"]+)"[^>]*>([^<]+)</.exec(html);
  if (!lic || lic[1] !== CC0_URL || !/CC0 1\.0/.test(lic[2])) throw new Error(`${t.title}: the page does not show CC0 1.0 (found ${lic ? `${lic[2].trim()} ${lic[1]}` : 'no licence'})`);
  const others = [...html.matchAll(/creativecommons\.org\/licenses\/([a-z-]+)\//g)].map((x) => x[1]);
  if (others.length) throw new Error(`${t.title}: the page also mentions CC ${others.join(', ')}: check it by hand`);
  const fileUrl = new URL(info.fileUrl);
  if (fileUrl.protocol !== 'https:' || !FMA_HOSTS.has(fileUrl.hostname)) throw new Error(`${t.title}: audio file is not on freemusicarchive.org (${fileUrl.hostname})`);
  return { checkedAt: new Date().toISOString(), licence: lic[2].trim(), licenceUrl: lic[1], fileUrl: fileUrl.href };
}

async function download(url, file) {
  let res;
  try { res = await fetch(url, { headers: { 'User-Agent': USER_AGENT }, signal: AbortSignal.timeout(120000) }); }
  catch (e) { throw new Error(`download from ${new URL(url).hostname} failed: ${e.cause?.code || e.message}`); }
  if (!res.ok) {
    const body = await res.text().catch(() => '');
    throw new Error(`download from ${new URL(url).hostname} returned HTTP ${res.status}${/agent proxy|no rule/i.test(body) ? ` (blocked by the network proxy: ${body.trim().slice(0, 120)})` : ''}`);
  }
  if (!/audio|octet-stream/.test(res.headers.get('content-type') || '')) throw new Error(`download from ${new URL(url).hostname} is ${res.headers.get('content-type')}, not audio`);
  const buf = Buffer.from(await res.arrayBuffer());
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(`${file}.part`, buf);
  fs.renameSync(`${file}.part`, file);
}

/**
 * Make every track of the manifest available in `cache` and check its SHA-256 against the manifest.
 *   cc0:    false skips the CC0 downloads (generated tracks only)
 *   strict: a missing CC0 track or a hash mismatch throws instead of warning
 *   pin:    record the hash of tracks that have none yet (or whose hash changed: generated tracks only) in the manifest
 * Returns [{ track, file, sha256, bytes, verification? }] for the tracks that are available, in manifest order.
 */
export async function prepareTracks({ cache = DEFAULT_CACHE, cc0 = true, strict = false, pin = false, force = false, log = console.log } = {}) {
  const manifest = loadManifest();
  const out = [], problems = [];
  const gen = manifest.tracks.filter((t) => t.kind === 'generated');
  const genDir = path.join(cache, 'generated');
  await makeDemoLibrary(genDir, { tracks: gen.map(generatorDef), force, log: (s) => log(`[generate] ${s.trim()}`) });
  let changed = false;
  for (const t of manifest.tracks) {
    let file, verification;
    if (t.kind === 'generated') file = path.join(genDir, t.file);
    else {
      if (!cc0) { log(`[cc0] skipped ${t.title} (--no-cc0)`); continue; }
      const src = path.join(cache, 'cc0-source', t.file);
      file = path.join(cache, 'cc0', t.file);
      try {
        verification = await verifyFmaPage(t);
        log(`[cc0] ${t.title}: ${verification.licence} confirmed on ${t.pageUrl}`);
        if (verification.fileUrl !== t.fileUrl) throw new Error(`the page now links ${verification.fileUrl} (manifest: ${t.fileUrl}); update the manifest after checking it`);
        if (!fs.existsSync(src)) { log(`[cc0] downloading ${t.fileUrl}`); await download(t.fileUrl, src); }
        const srcSha = sha256File(src);
        if (t.sourceSha256 && t.sourceSha256 !== srcSha) { fs.rmSync(src); throw new Error(`downloaded file SHA-256 ${srcSha} does not match the manifest (${t.sourceSha256})`); }
        if (!t.sourceSha256) { if (pin) { t.sourceSha256 = srcSha; changed = true; log(`[hash] pinned source ${t.title} ${srcSha}`); } else log(`[hash] ${t.title}: source has no pinned hash yet (${srcSha}); --pin records it`); }
        verification.sourceSha256 = srcSha;
        packCopy(src, file, t);
      } catch (e) {
        const msg = `${t.title}: ${e.message}`;
        problems.push(msg); log(`[cc0] NOT INCLUDED: ${msg}`);
        continue;
      }
    }
    const sha256 = sha256File(file), bytes = fs.statSync(file).size;
    if (t.sha256 && t.sha256 !== sha256) {
      // derived files: the toolchain (V8 maths, ffmpeg, Chromium for covers) can change the bytes, not the music
      const msg = `${t.title}: pack file SHA-256 ${sha256} differs from the manifest (${t.sha256})`;
      if (pin) { t.sha256 = sha256; t.bytes = bytes; changed = true; log(`[hash] re-pinned ${t.title}`); }
      else { problems.push(msg); log(`[hash] WARNING ${msg} (different ffmpeg / Chromium / Node? --pin records the new hash)`); }
    } else if (!t.sha256 && pin) { t.sha256 = sha256; t.bytes = bytes; changed = true; log(`[hash] pinned ${t.title} ${sha256}`); }
    else if (!t.sha256) log(`[hash] ${t.title} has no pinned hash yet (${sha256}); --pin records it`);
    if (verification && pin) {
      const result = `${verification.licence} shown on the track page; downloaded file SHA-256 ${verification.sourceSha256}`;
      const today = verification.checkedAt.slice(0, 10);
      t.pageCheck = [...(t.pageCheck || []).filter((c) => !(c.date === today && c.result === result)), { date: today, result }].slice(-5);
      changed = true;
    }
    out.push({ track: t, file, sha256, bytes, verification });
  }
  if (changed && pin) saveManifest(manifest);
  if (strict && problems.length) throw new Error(`review pack incomplete:\n  ${problems.join('\n  ')}`);
  return { tracks: out, problems, manifest };
}

/** The copy that goes into the pack: same audio stream, no embedded artwork (artist logos), licence in the comment. */
function packCopy(src, dst, t) {
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  const r = spawnSync(ffmpegPath(), ['-hide_banner', '-loglevel', 'error', '-y', '-i', src, '-map', '0:a', '-c', 'copy', '-map_metadata', '0', '-id3v2_version', '3', '-write_xing', '1',
    '-metadata', `comment=CC0 1.0 (public domain dedication) - ${t.pageUrl}`, '-metadata', 'TDAT=', '-fflags', '+bitexact', dst], { stdio: ['ignore', 'inherit', 'inherit'] });
  if (r.status !== 0) throw new Error(`ffmpeg could not copy ${src}`);
}

/** BPM / key / loudness with OpenDJ's analysis (the same pure functions as the app's analysis worker). */
export function analyseFile(file, sr = 44100) {
  const r = spawnSync(ffmpegPath(), ['-hide_banner', '-loglevel', 'error', '-i', file, '-ac', '1', '-ar', String(sr), '-f', 'f32le', '-'], { maxBuffer: 1 << 30 });
  if (r.status !== 0) throw new Error(`ffmpeg could not decode ${file}`);
  const mono = new Float32Array(r.stdout.buffer, r.stdout.byteOffset, r.stdout.byteLength / 4);
  const a = analyzeTrack(new Float32Array(mono), sr);
  return { bpm: Math.round(a.bpm * 100) / 100, key: a.key, camelot: toCamelot(a.key), duration: Math.round(mono.length / sr * 10) / 10 };
}

const mmss = (s) => `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, '0')}`;

/** CREDITS.md for the zip and docs/store/CREDITS.md. `included`: the prepared tracks (null = every manifest track). */
export function creditsMarkdown(manifest, included = null) {
  const inc = included ? new Set(included.map((x) => x.track.id)) : null;
  const rows = manifest.tracks.filter((t) => !inc || inc.has(t.id));
  const missing = inc ? manifest.tracks.filter((t) => !inc.has(t.id)) : [];
  const m = (t) => {
    if (!t.measured) return 'not measured yet';
    const bpm = `${Number.isInteger(t.measured.bpm) ? t.measured.bpm : t.measured.bpm.toFixed(1)} BPM`;
    if (t.kind !== 'generated') return `${bpm}, ${t.measured.key} (${t.measured.camelot})`;
    const tagged = generatorKey(t), cam = toCamelot(tagged);
    return tagged === t.measured.key ? `${bpm}, ${tagged} (${cam})` : `${bpm}, ${tagged} (${cam}) as composed and tagged; the key detector hears ${t.measured.key} (${t.measured.camelot})`;
  };
  const L = [];
  L.push('# OpenDJ review pack: credits and licences', '');
  L.push('Every track in this pack is free of third-party rights: it is either an **original track generated by the OpenDJ project** and released under **CC0 1.0**, or a third-party track whose official page shows **CC0 1.0** (public-domain dedication) at the time it was downloaded. CC0 needs no credit; it is given below as a courtesy.', '');
  L.push('No AI-service output, no CC BY / BY-SA / NC / ND tracks and no samples of other recordings are included. BPM and key were measured with OpenDJ\'s own analysis.', '');
  L.push('| # | Track | Artist | Licence | Source | BPM / key (OpenDJ) | SHA-256 |', '|---|---|---|---|---|---|---|');
  for (const [i, t] of rows.entries()) {
    const src = t.kind === 'generated' ? 'Generated by `scripts/demo/make-demo-library.mjs` (OpenDJ project)' : `[Free Music Archive](${t.pageUrl})`;
    L.push(`| ${i + 1} | ${t.title} | ${t.artist} | [CC0 1.0](${t.licenceUrl}) | ${src} | ${m(t)} | ${t.sha256 ? `\`${t.sha256}\`` : 'not pinned yet'} |`);
  }
  L.push('', '## Credit lines', '');
  for (const t of rows) L.push(`- ${t.kind === 'generated' ? `"${t.title}" (${t.genre}): OpenDJ project, CC0 1.0. An original synthesised track: no samples, loops or recordings of anyone else.` : `${t.credit} The copy in this pack has the embedded cover art removed (it shows the artist's logo); the audio is the downloaded file's, unchanged (downloaded file SHA-256 \`${t.sourceSha256 || 'not pinned yet'}\`).`}`);
  if (missing.length) {
    L.push('', '## Listed but not in this copy', '');
    for (const t of missing) L.push(`- "${t.title}" by ${t.artist}: ${t.status || 'not downloaded when this pack was built'}`);
  }
  L.push('', '## Licence verification', '');
  for (const t of rows.filter((x) => x.kind === 'cc0')) for (const c of t.pageCheck || []) L.push(`- ${c.date}: "${t.title}" by ${t.artist}: ${c.result}`);
  if (!rows.some((x) => x.kind === 'cc0')) L.push('- This copy contains only the generated tracks (no third-party audio).');
  L.push('', 'The OpenDJ app itself is MIT-licensed: see `LICENSE` and `THIRD_PARTY_NOTICES.md` in the repository.', '');
  return L.join('\n');
}

export const checksumsText = (files) => files.map(({ name, sha256 }) => `${sha256}  ${name}`).join('\n') + '\n';

/** Minimal zip writer (stored MP3s, deflated text), no dependencies. entries: [{ name, data: Buffer, mtime? }] */
export function writeZip(file, entries) {
  const parts = [], central = [];
  let off = 0;
  const dos = (d) => { const t = ((d.getHours() << 11) | (d.getMinutes() << 5) | (d.getSeconds() >> 1)) & 0xffff; const dt = (((d.getFullYear() - 1980) << 9) | ((d.getMonth() + 1) << 5) | d.getDate()) & 0xffff; return [t, dt]; };
  for (const e of entries) {
    const name = Buffer.from(e.name, 'utf8');
    const deflate = !/\.(mp3|m4a|mp4|jpg|png|zip)$/i.test(e.name);
    const body = deflate ? zlib.deflateRawSync(e.data, { level: 9 }) : e.data;
    const crc = zlib.crc32(e.data);
    const [t, d] = dos(e.mtime || new Date());
    const h = Buffer.alloc(30); h.writeUInt32LE(0x04034b50, 0); h.writeUInt16LE(20, 4); h.writeUInt16LE(0x0800, 6); h.writeUInt16LE(deflate ? 8 : 0, 8);
    h.writeUInt16LE(t, 10); h.writeUInt16LE(d, 12); h.writeUInt32LE(crc, 14); h.writeUInt32LE(body.length, 18); h.writeUInt32LE(e.data.length, 22); h.writeUInt16LE(name.length, 26); h.writeUInt16LE(0, 28);
    parts.push(h, name, body);
    const c = Buffer.alloc(46); c.writeUInt32LE(0x02014b50, 0); c.writeUInt16LE(20, 4); c.writeUInt16LE(20, 6); c.writeUInt16LE(0x0800, 8); c.writeUInt16LE(deflate ? 8 : 0, 10);
    c.writeUInt16LE(t, 12); c.writeUInt16LE(d, 14); c.writeUInt32LE(crc, 16); c.writeUInt32LE(body.length, 20); c.writeUInt32LE(e.data.length, 24); c.writeUInt16LE(name.length, 28); c.writeUInt32LE(off, 42);
    central.push(c, name);
    off += 30 + name.length + body.length;
  }
  const cd = Buffer.concat(central);
  const end = Buffer.alloc(22); end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(entries.length, 8); end.writeUInt16LE(entries.length, 10); end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(off, 16);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, Buffer.concat([...parts, cd, end]));
}

