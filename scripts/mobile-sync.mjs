// Prepares the mobile app's web assets: copies public/ (the same UI as the desktop and web app) to mobile/www, the
// Capacitor webDir, then runs `npx cap sync` (copies them into the Android / iOS projects and updates native plugins).
// The desktop app and the server keep serving public/ directly; mobile/www is generated (git-ignored).
// Usage: node scripts/mobile-sync.mjs [--no-cap] [android|ios]
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'public');
const out = path.join(root, 'mobile', 'www');
// not used inside the app: the hosted-mode login page and the PWA service worker
const SKIP = new Set(['login.html', 'sw.js']);

fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(src, out, { recursive: true, filter: (p) => !SKIP.has(path.relative(src, p)) && !p.endsWith('.map') });
// Store builds: where "Update now" goes (public/js/update-config.js; default: GitHub releases)
const env = process.env;
if (env.OPENDJ_UPDATE_CHANNEL || env.OPENDJ_PLAY_URL || env.OPENDJ_APPSTORE_URL || env.OPENDJ_TESTFLIGHT_URL) {
  const { UPDATE_CONFIG } = await import(new URL('../public/js/update-config.js', import.meta.url));
  const channel = env.OPENDJ_UPDATE_CHANNEL || UPDATE_CONFIG.channel;
  if (!['github', 'play', 'appstore'].includes(channel)) throw new Error(`OPENDJ_UPDATE_CHANNEL must be github, play or appstore (got "${channel}")`);
  const https = (name, v) => { if (v && !/^https:\/\/[^\s"'<>\\]+$/.test(v)) throw new Error(`${name} must be an https URL`); return v; };
  const cfg = {
    channel,
    playUrl: https('OPENDJ_PLAY_URL', env.OPENDJ_PLAY_URL) || UPDATE_CONFIG.playUrl,
    appStoreUrl: https('OPENDJ_APPSTORE_URL', env.OPENDJ_APPSTORE_URL) || UPDATE_CONFIG.appStoreUrl,
    testFlightUrl: https('OPENDJ_TESTFLIGHT_URL', env.OPENDJ_TESTFLIGHT_URL) || UPDATE_CONFIG.testFlightUrl,
  };
  fs.writeFileSync(path.join(out, 'js', 'update-config.js'), `// Generated by scripts/mobile-sync.mjs\nexport const UPDATE_CONFIG = ${JSON.stringify(cfg, null, 2)};\n`);
  console.log(`update channel: ${cfg.channel}`);
}
let files = 0, bytes = 0;
(function count(d) { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) count(p); else { files++; bytes += fs.statSync(p).size; } } })(out);
console.log(`mobile/www: ${files} files, ${(bytes / 1048576).toFixed(1)} MB`);

if (!process.argv.includes('--no-cap')) {
  const platform = process.argv.slice(2).find((a) => a === 'android' || a === 'ios');
  execFileSync(process.platform === 'win32' ? 'npx.cmd' : 'npx', ['cap', 'sync', ...(platform ? [platform] : [])], { cwd: root, stdio: 'inherit' });
}
