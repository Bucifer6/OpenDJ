// Builds public/vendor/opendj-vendor.js: the npm libraries the mobile app's on-device backend needs in the browser,
// as one ES module (the UI has no build step, so this file is committed; rebuild it after updating these packages):
//   music-metadata (browser build: parseBlob / parseBuffer)  - tags + cover art of imported files
//   fast-xml-parser (XMLParser)                               - rekordbox XML import
//   @capacitor/core (registerPlugin, CapacitorHttp)           - native plugins (only used inside the iOS / Android app)
// Usage: node scripts/build-vendor.mjs [--check]   (--check: fail if the committed file is out of date)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'public', 'vendor', 'opendj-vendor.js');
const pkgs = ['music-metadata', 'fast-xml-parser', '@capacitor/core'];
const version = (p) => JSON.parse(fs.readFileSync(path.join(root, 'node_modules', p, 'package.json'), 'utf8')).version;
const banner = `/*! OpenDJ vendor bundle (generated by scripts/build-vendor.mjs - do not edit).\n${pkgs.map((p) => ` *  ${p}@${version(p)} (MIT)`).join('\n')}\n * See THIRD_PARTY_NOTICES.md. */`;

const entry = `export { parseBlob, parseBuffer, parseWebStream } from 'music-metadata';
export { XMLParser } from 'fast-xml-parser';
export { Capacitor, registerPlugin, CapacitorHttp } from '@capacitor/core';`;

const r = await build({
  stdin: { contents: entry, resolveDir: root, loader: 'js' },
  bundle: true, format: 'esm', platform: 'browser', target: ['es2020', 'safari15'], minify: true,
  legalComments: 'none', banner: { js: banner }, write: false, logLevel: 'warning',
  define: { 'process.env.NODE_ENV': '"production"', 'process.env.DEBUG': 'undefined' },
});
const code = r.outputFiles[0].text;
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== code) { console.error('public/vendor/opendj-vendor.js is out of date: run node scripts/build-vendor.mjs'); process.exit(1); }
  console.log('vendor bundle up to date');
} else {
  fs.writeFileSync(out, code);
  console.log(`wrote ${path.relative(root, out)} (${(code.length / 1024).toFixed(0)} KB)`);
}
